import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { WebSocket } from 'ws';

test('connected table: privacy, limits, idempotency, chat, crews and atomic coins', {timeout: 30000}, async t => {
  const data = await mkdtemp(join(tmpdir(), 'street-circle-test-'));
  const child = spawn(process.execPath, ['index.mjs'], { cwd: new URL('..', import.meta.url), env: { ...process.env, PORT: '0', DATA_DIR: data, NODE_ENV: 'development', ALLOW_GUESTS: 'true', TWILIO_ACCOUNT_SID: '', LIVEKIT_API_KEY: '' }, stdio: ['ignore', 'pipe', 'pipe'] });
  const sockets = [];
  t.after(async () => { for (const ws of sockets) ws.terminate(); const ended = once(child, 'exit'); child.kill(); await ended; await rm(data, {recursive: true, force: true}); });
  const url = await new Promise((resolve, reject) => {
    let output = '';
    child.stdout.on('data', b => { output += b; const match = output.match(/http:\/\/localhost:(\d+)/); if (match) resolve(`http://127.0.0.1:${match[1]}`); });
    child.once('error', reject); child.once('exit', code => reject(new Error(`Server exited ${code}`)));
  });
  async function api(path, token, body, method = body ? 'POST' : 'GET') {
    const response = await fetch(`${url}/api${path}`, {method, headers: {'Content-Type':'application/json', ...(token ? {Authorization:`Bearer ${token}`} : {})}, body: body ? JSON.stringify(body) : undefined});
    return {status:response.status, data:await response.json()};
  }
  const a = (await api('/auth/guest', null, {name:'AdaTest'})).data;
  const b = (await api('/auth/guest', null, {name:'BoTest'})).data;
  const c = (await api('/auth/guest', null, {name:'CyTest'})).data;
  assert.equal((await api('/me')).status, 401);
  assert.equal((await api('/auth/guest', null, {name:'adatest'})).status, 400);
  assert.equal((await api('/auth/sms', null, {phone:'+15551234567',consent:true})).status, 503);
  const created = await api('/rooms', a.token, {name:'Review circle',ante:50,private:true});
  const roomId = created.data.id, invite = created.data.inviteCode;
  assert.equal((await api('/rooms', c.token)).data.length, 0);
  assert.equal((await api(`/rooms/${roomId}`, c.token)).status, 404);
  await api('/rooms/join', b.token, {code:invite});
  await api('/rooms/join', c.token, {code:invite,watch:true});
  const ticket = (await api('/socket-ticket', a.token, {})).data.ticket;
  const ws = new WebSocket(url.replace('http:', 'ws:') + '/ws'); sockets.push(ws);
  await once(ws,'open');
  const ready = once(ws,'message'); ws.send(JSON.stringify({ticket}));
  assert.equal(JSON.parse((await ready)[0]).type,'ready');
  const replay = new WebSocket(url.replace('http:', 'ws:') + '/ws'); sockets.push(replay);
  await once(replay,'open'); const closed = once(replay,'close'); replay.send(JSON.stringify({ticket}));
  assert.equal((await closed)[0],1008);
  let table = (await api(`/rooms/${roomId}/start`,a.token,{})).data;
  assert.equal(table.game.players[0].dice.length,5);
  assert.equal(table.game.players[1].dice.length,0);
  const watch = (await api(`/rooms/${roomId}`,c.token)).data;
  assert.ok(watch.game.players.every(p=>p.dice.length===0));
  assert.equal((await api('/me',a.token)).data.coins,950);
  assert.equal((await api('/me',b.token)).data.coins,950);
  assert.equal((await api(`/rooms/${roomId}/start`,a.token,{})).status,400);
  assert.equal((await api('/me',a.token)).data.coins,950);
  const action = {requestId:'test-bid-1',revision:0,action:{type:'bid',quantity:1,face:2}};
  table = (await api(`/rooms/${roomId}/action`,a.token,action)).data;
  assert.equal(table.game.revision,1);
  assert.equal((await api(`/rooms/${roomId}/action`,a.token,action)).data.game.revision,1);
  assert.equal((await api(`/rooms/${roomId}/action`,b.token,{requestId:'stale',revision:0,action:{type:'catch'}})).status,409);
  assert.equal((await api(`/rooms/${roomId}/action`,c.token,{requestId:'watch-action',revision:1,action:{type:'catch'}})).status,400);
  await api(`/rooms/${roomId}/chat`,b.token,{text:'Hello circle'});
  assert.equal((await api(`/rooms/${roomId}`,a.token)).data.chat[0].text,'Hello circle');
  assert.equal((await api(`/rooms/${roomId}/video-token`,c.token,{})).status,503);
  await api(`/rooms/${roomId}/leave`,b.token,{});
  assert.equal((await api('/me',a.token)).data.coins,1050);
  assert.equal((await api('/me',b.token)).data.coins,950);
  await api(`/rooms/${roomId}`,a.token);
  assert.equal((await api('/me',a.token)).data.coins,1050);
  const crew = (await api('/crews',a.token,{name:'Test crew'})).data;
  assert.equal((await api('/crews/join',c.token,{code:crew.code})).status,200);
  assert.equal((await api('/crews',a.token)).data[0].members.length,2);
  await api('/me',b.token,{private:true},'PATCH');
  assert.ok(!(await api('/players?q=Bo',a.token)).data.some(p=>p.id===b.user.id));
  await api(`/blocks/${c.user.id}`,a.token,{blocked:true});
  assert.ok(!(await api('/players',a.token)).data.some(p=>p.id===c.user.id));
  assert.equal((await api('/me',a.token,{dailyMinutes:1},'PATCH')).status,400);
  assert.equal((await api('/me',a.token,{dailyMinutes:5},'PATCH')).status,200);
});
